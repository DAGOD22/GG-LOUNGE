/**
 * Controls for one game: the specific entry when we have one, otherwise a
 * genre hint that at least names the input devices the game expects.
 */
export function getGameControls(id: string | undefined | null, genre?: string): string {
  if (id && GAME_CONTROLS[id]) return GAME_CONTROLS[id]
  const key = (genre || '').toLowerCase()
  if (key === 'idle') return 'Mostly mouse — click to earn, then buy upgrades'
  if (key === 'puzzle') return 'Mouse and keyboard — click to interact'
  if (key === 'racing') return 'Arrows or WASD to steer'
  if (key === 'battle') return 'WASD to move • Mouse to aim • Click to shoot'
  return 'Arrows / WASD • Space • Enter'
}
